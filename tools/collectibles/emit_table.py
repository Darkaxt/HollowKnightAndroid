"""Turn an extractor's JSON into the generated C# table (#37).

Usage:  python -I emit_table.py <in.json> <out.cs> <namespace> <class>

The output is the text DualSouls.Mods.CollectibleTable.Parse reads:
"S|scene|width|height" per room, then "P|scene|kind|key|x|y" per collectible.
"""
import json
import sys


def main(src, out, namespace, cls):
    d = json.load(open(src, encoding="utf-8"))
    entries, seen = [], set()
    for e in d["entries"]:
        # One pin per kind and save key per room (a few rooms hold variants of one item).
        ident = (e["scene"], e["kind"], e["key"])
        if e["scene"] in d["sizes"] and ident not in seen:
            seen.add(ident)
            entries.append(e)
    dropped = len(d["entries"]) - len(entries)
    scenes = sorted({e["scene"] for e in entries})
    lines = [f"S|{s}|{d['sizes'][s][0]}|{d['sizes'][s][1]}" for s in scenes]
    for e in sorted(entries, key=lambda e: (e["scene"], e["kind"], e["key"], e["x"], e["y"])):
        for f in (e["scene"], e["kind"], e["key"]):
            if "|" in f or "\n" in f or '"' in f:
                raise ValueError(f"unsafe field {f!r}")
        lines.append(f"P|{e['scene']}|{e['kind']}|{e['key']}|{e['x']:g}|{e['y']:g}")
    body = "\n".join(lines)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// <auto-generated> tools/collectibles/emit_table.py from the game's own scene data (#37).\n")
        f.write("// Room names, positions and save keys only. Regenerate; do not edit.\n")
        cls_text = f"internal static class {cls}\n{{\n    public const string Table = @\"{body}\";\n}}\n"
        if namespace:
            # Not indented: the table's lines are verbatim string content.
            f.write(f"namespace {namespace}\n{{\n{cls_text}}}\n")
        else:
            f.write(cls_text)
    print(f"{len(entries)} spots in {len(scenes)} rooms; {dropped} dropped (no tilemap size or duplicate)", file=sys.stderr)


if __name__ == "__main__":
    main(*sys.argv[1:5])
