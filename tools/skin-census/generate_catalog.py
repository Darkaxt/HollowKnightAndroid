"""Generate the Silksong skin catalog from a SkinCensus TSV (dev-only, #63).

Usage: python -I generate_catalog.py <census.tsv> <repo root>

Writes, all LF and deterministic:
  docs/superpowers/specs/data/silksong-collections-1.0.29980.tsv   (the census, for provenance)
  docs/superpowers/specs/data/silksong-skin-catalog-v1.txt         (one canonical path per line)
  tools/silksong-patches/src/skins/runtime/SilksongSkinCatalog.g.cs
  src/SilksongLauncher.Launcher/app/src/main/kotlin/dev/silksong/launcher/skins/catalog/SilksongCatalogData.kt
and prints the catalog id and SHA-256 to pin in SkinCatalogProfiles.kt.

One target per distinct atlas texture of a collection: "Assets/Collections/<name> Data/<texture>.png".
The 16 targets of the previous catalog come first, in their old order, so packs imported against it stay valid.
"""
import csv
import hashlib
import pathlib
import re
import sys

LEGACY = [
    "Hornet Cln/atlas0", "Hornet Cloakless Cln/atlas0", "Hornet CrestWeapon Dagger Cln/atlas0",
    "Hornet CrestWeapon Drill Lance Cln/atlas0", "Hornet CrestWeapon Scythe/atlas0",
    "Hornet CrestWeapon Shaman Cln/atlas0", "Hornet CrestWeapon Warrior Cln/atlas0",
    "Hornet CrestWeapon Whip Cln/atlas0", "Hornet_Needolin_Windy/atlas0", "HUD Cln/atlas0",
    "HUD Extras Cln/atlas0", "Knight/atlas0", "Knight/atlas1", "Knight/atlas2", "Knight/atlas3",
    "Bone Beast Child Call Cln/atlas0",
]
SAFE = re.compile(r"^[A-Za-z0-9 _'()&.,+-]+$")


def family(name, bundle):
    if bundle.startswith("herocollections_"):
        return "Character"
    if bundle.startswith("hud_") or name == "HUD Frame Steel Soul Cln":
        return "Hud"
    if bundle.startswith(("tk2dcollections_assets_ui.", "heartpieceupgrade_", "shopui_")):
        return "Ui"
    return "World"


def main():
    census, repo = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    raw = census.read_bytes()
    rows = list(csv.DictReader(raw.decode("utf-8").splitlines(), delimiter="\t"))
    collections = {}
    for row in rows:
        key = (row["collection"], row["bundle"])
        collections.setdefault(key, []).append(row)

    by_name, excluded = {}, []
    for (name, bundle), pages in sorted(collections.items()):
        reason = None
        if not name or not SAFE.match(name) or name.strip() != name:
            reason = "unsafe or empty name"
        elif any(p["texture"] == "?" or int(p["page"]) < 0 for p in pages):
            reason = "unresolved material page"
        elif not SAFE.match("".join(p["texture"] for p in pages)):
            reason = "unsafe texture name"
        if reason:
            excluded.append((name or "<empty>", bundle, reason))
            continue
        shape = tuple((p["materials"], p["page"], p["texture"], p["width"], p["height"]) for p in pages)
        if name in by_name and by_name[name][1] != shape:
            by_name[name] = (None, None)
            continue
        if name not in by_name:
            by_name[name] = (bundle, shape)
    for name in [n for n, v in by_name.items() if v[0] is None]:
        excluded.append((name, "*", "same name with different atlas layout"))
        del by_name[name]

    targets = {}
    for name, (bundle, shape) in by_name.items():
        materials = int(shape[0][0])
        dims = {}
        for _, _, texture, width, height in shape:
            if texture in dims and dims[texture] != (int(width), int(height)):
                dims = None
                break
            dims[texture] = (int(width), int(height))
        if dims is None:
            excluded.append((name, bundle, "one texture name with two sizes"))
            continue
        for texture, (width, height) in dims.items():
            targets[f"{name}/{texture}"] = (name, texture, width, height, materials, family(name, bundle))

    missing = [x for x in LEGACY if x not in targets]
    if missing:
        raise SystemExit(f"legacy targets missing from census: {missing}")
    order = LEGACY + sorted((k for k in targets if k not in LEGACY), key=lambda k: k.encode("utf-8"))
    path = lambda key: f"Assets/Collections/{targets[key][0]} Data/{targets[key][1]}.png"
    catalog = "".join(path(k) + "\n" for k in order).encode("utf-8")
    digest = hashlib.sha256(catalog).hexdigest()
    catalog_id = f"silksong-1.0.29980-collections-{len(order)}"

    data = repo / "docs/superpowers/specs/data"
    (data / "silksong-collections-1.0.29980.tsv").write_bytes(raw)
    (data / "silksong-skin-catalog-v1.txt").write_bytes(catalog)

    cs = ["// <auto-generated> by tools/skin-census/generate_catalog.py from the 1.0.29980 depot census (#63).",
          "// Do not edit by hand: rerun the census and the generator instead.",
          "namespace DualSouls.Skins.Silksong.Runtime",
          "{",
          "    public static partial class SilksongSkinTargets",
          "    {",
          f"        public const string CatalogId = \"{catalog_id}\";",
          "        // A method, not a field: static field initializers of a partial class run in an unspecified file order.",
          "        static (string Collection, string Texture, int Width, int Height, int Materials, SilksongSkinFamily Family)[] CatalogRows() => new[]",
          "        {"]
    for key in order:
        name, texture, width, height, materials, fam = targets[key]
        cs.append(f"            (\"{name}\", \"{texture}\", {width}, {height}, {materials}, SilksongSkinFamily.{fam}),")
    cs += ["        };", "    }", "}", ""]
    (repo / "tools/silksong-patches/src/skins/runtime/SilksongSkinCatalog.g.cs").write_text(
        "\n".join(cs), encoding="utf-8", newline="\n")

    kt = ["// Generated by tools/skin-census/generate_catalog.py from the 1.0.29980 depot census (#63). Do not edit.",
          "package dev.silksong.launcher.skins.catalog", "",
          "internal object SilksongCatalogData {",
          f"    const val CATALOG_ID = \"{catalog_id}\"",
          f"    const val SHA256 = \"{digest}\"",
          f"    const val PATH_COUNT = {len(order)}", "",
          "    /** Catalog rows in order with their exact original atlas size. */",
          "    val ROWS: List<Triple<String, Int, Int>> = listOf("]
    for key in order:
        kt.append(f"        Triple(\"{path(key)}\", {targets[key][2]}, {targets[key][3]}),")
    kt += ["    )", "}", ""]
    (repo / "src/SilksongLauncher.Launcher/app/src/main/kotlin/dev/silksong/launcher/skins/catalog/SilksongCatalogData.kt").write_text(
        "\n".join(kt), encoding="utf-8", newline="\n")

    counts = {}
    for key in order:
        counts[targets[key][5]] = counts.get(targets[key][5], 0) + 1
    print(f"catalog {catalog_id} sha256 {digest}")
    print("families", counts)
    for item in excluded:
        print("excluded", *item, sep="\t")


main()
